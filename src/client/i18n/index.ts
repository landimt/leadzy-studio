export function isApiErrorCode(value: unknown): value is ApiErrorCode {
  return typeof value === 'string' && Object.hasOwn(API_ERROR_MESSAGE_KEY, value);
}

export function apiErrorMessage(code: ApiErrorCode, fallback: string): string {
  const key = API_ERROR_MESSAGE_KEY[code];
  return key === null ? fallback : t(key);
}
