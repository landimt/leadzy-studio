let currentLocale: AppLocale = 'pt-BR';

export function setLocale(locale: AppLocale): void {
  currentLocale = locale;
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
}

export function getLocale(): AppLocale {
  return currentLocale;
}

function message(key: MessageKey): string {
  return currentLocale === 'en' ? (en[key] ?? ptBR[key]) : ptBR[key];
}

export function t(key: MessageKey): string {
  return message(key);
}

/** `t` with `{name}` placeholders filled in; an unknown placeholder stays visible rather than vanishing. */
export function tf(key: MessageKey, vars: Readonly<Record<string, string>>): string {
  return message(key).replace(
    /\{(\w+)\}/g,
    (placeholder, name: string) => vars[name] ?? placeholder,
  );
}

